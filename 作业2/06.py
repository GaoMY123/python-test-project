# a = ['赵', '钱', '孙', '李']

# b = ['一', '二', '三', '四']
def main():
    a=['赵','钱','孙','李']
    b=['一','二','三','四']
    c=[]
    for i in a:
        for j in b:
            c.append(i+j)
    print(c)
if __name__=="__main__":
    main()
